section('§4  v3.0.13 GUARD — an unkeyed provider\'s models are NOT selectable');
// ═════════════════════════════════════════════════════════════════════════
{
  for (const only of ALL_PROVIDERS) {
    const other = ALL_PROVIDERS.find(p => p !== only);
    const { norm, html } = menuFor([only]);
    for (const e of REAL[other]) {
      ok(resolveChatModel(e.id, norm, [only]) === null,
        `key=${only} only → resolveChatModel refuses "${other}" model "${e.id}"`);
      ok(!html.includes('data-model-id="' + e.id + '"'),
        `key=${only} only → no selectable row exists for "${e.id}"`);
    }
    for (const e of REAL[only]) {
      const r = resolveChatModel(e.id, norm, [only]);
      ok(r !== null && r.provider === only && r.entry.id === e.id,
        `key=${only} only → its own model "${e.id}" resolves, tagged provider "${only}"`);
    }
  }
  // Zero keys: NOTHING resolves, from either provider.
  const noneNorm = normalizeOfferable(serverOfferable([]), []);
  for (const p of ALL_PROVIDERS) for (const e of REAL[p]) {
    ok(resolveChatModel(e.id, noneNorm, []) === null, `zero keys → "${e.id}" is not selectable`);
  }
  // COMPOSITION CONTROL: the payload the server actually sends today (already
  // gated its side) must give the SAME answer as the ungated one every other
  // assertion in §3/§4 uses. If these two ever diverge, one of the two layers
  // is doing something the other is not.
  for (const only of ALL_PROVIDERS) {
    const clientScoped = normalizeOfferable(rawFull(), [only]);
    const serverScoped = normalizeOfferable(serverOfferable([only]), [only]);
    ok(renderModelMenuHtml(clientScoped, [only], null) === renderModelMenuHtml(serverScoped, [only], null),
      `key=${only} only → client-side scoping of the FULL catalogue matches the server-gated payload byte-for-byte`);
  }
  // LAYER 2, DRIVEN INDEPENDENTLY. `normalizeOfferable` (layer 1) empties the
  // unkeyed provider's list, which MASKS the provider loop inside
  // `offerableEntries`/`renderModelMenuHtml` (layer 2): mutating layer 2 alone
  // leaves every assertion above green, because layer 1 has already removed
  // anything for it to leak. Rather than report that as coverage it does not
  // have, these assertions hand the SECOND layer a map that was never scoped —
  // exactly the state if layer 1 ever regressed — so layer 2 is load-bearing
  // here on its own.
  for (const only of ALL_PROVIDERS) {
    const other = ALL_PROVIDERS.find(p => p !== only);
    const unscoped = Object.assign(Object.create(null), rawFull());
    ok(offerableEntries(unscoped, [only]).length === REAL[only].length,
      `unscoped map + key=${only} → offerableEntries still yields only that provider's ${REAL[only].length} models`);
    ok(REAL[other].every(e => resolveChatModel(e.id, unscoped, [only]) === null),
      `unscoped map + key=${only} → resolveChatModel still refuses every "${other}" model`);
    const html = renderModelMenuHtml(unscoped, [only], null);
    ok(REAL[other].every(e => !html.includes('data-model-id="' + e.id + '"')),
      `unscoped map + key=${only} → no "${other}" row reaches the rendered menu`);
    ok(offerableEntries(unscoped, []).length === 0,
      `unscoped map + ZERO keys → nothing is pickable (${only} pass)`);
  }
  const rescoped = normalizeOfferable(rawFull(), ['gemini']);
  ok(resolveChatModel('__proto__', rescoped, ['gemini']) === null, 'prototype-key model id is refused');
  for (const bad of [null, undefined, '', 0, {}, []]) {
    ok(resolveChatModel(bad, rescoped, ['gemini']) === null, `garbage model id ${JSON.stringify(bad)} is refused`);
  }
}

