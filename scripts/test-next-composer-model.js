section('§9  Backend-capability drift guard');
// ═════════════════════════════════════════════════════════════════════════
/*
 * The picker is gated OFF because the chat path drops a model id. The risk of a
 * build-time gate is the OPPOSITE drift: the backend lands, nobody flips the
 * constant, and a finished feature stays invisible forever.
 *
 * This checks the LIVE module — not source text — for a model-aware normaliser
 * on src/brain/chat.js's `__testing` surface, mirroring the existing
 * `normalizeChatProvider`. If one appears while the gate is still shut, this
 * FAILS and names the constant to flip. It never fails in the other direction:
 * a backend that lands support without such an export leaves the gate shut and
 * this green — recorded in NOT ENFORCED above as the deliberate safe direction.
 */
{
  const gateOn = /^const MODEL_PICKER_ENABLED = true;\s*$/m.test(chatSrc);
  const brain = await import('../src/brain/chat.js');
  const t = brain.__testing || {};
  const modelAware = Object.keys(t).some(k => /model/i.test(k));
  ok(typeof t.normalizeChatProvider === 'function',
    'control: src/brain/chat.js still exports normalizeChatProvider on __testing (the shape this guard mirrors)');
  if (modelAware && !gateOn) {
    ok(false, 'BACKEND MODEL SUPPORT DETECTED but MODEL_PICKER_ENABLED is still false — flip it in src/public/next/views/chat.js');
  } else if (modelAware && gateOn) {
    ok(true, 'backend exposes model normalisation and the picker gate is ON — consistent');
  } else {
    ok(!gateOn, 'backend exposes NO chat-model normalisation, so the picker gate is correctly OFF (model selection would be inert)');
  }
}

