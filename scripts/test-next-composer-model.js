// ── Extraction (brace-matched; a desync fails LOUDLY, never silently) ─────
function extractFunction(src, name) {
  const marker = new RegExp(`(?:^|\\n)(?:export\\s+)?(?:async\\s+)?function ${name}\\s*\\(`);
  const m = marker.exec(src);
  if (!m) throw new Error(`extractFunction: "${name}" not found in chat.js`);
  const start = m.index + (m[0].startsWith('\n') ? 1 : 0);
  let p = src.indexOf('(', start);
  if (p === -1) throw new Error(`extractFunction: "${name}" has no parameter list`);
  let parenDepth = 0;
  for (; p < src.length; p++) {
    if (src[p] === '(') parenDepth++;
    else if (src[p] === ')') { parenDepth--; if (parenDepth === 0) { p++; break; } }
  }
  let i = src.indexOf('{', p);
  if (i === -1) throw new Error(`extractFunction: "${name}" has no body`);
  let depth = 0;
  for (; i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}') { depth--; if (depth === 0) { i++; break; } }
  }
  const extracted = src.slice(start, i).replace(/^export\s+/, '');
  if (!/\n\}$/.test(extracted)) {
    throw new Error(`extractFunction: "${name}" extraction does not end at a top-level closing brace — the matcher desynced`);
  }
  return extracted;
}

/** Stops at the first `;` that ends a LINE, allowing a trailing // comment. */
function extractConst(src, name) {
  const re = new RegExp(`(?:^|\\n)(?:export\\s+)?const ${name} =[\\s\\S]*?;[ \\t]*(?://[^\\n]*)?\\n`, 'm');
  const m = re.exec(src);
  if (!m) throw new Error(`extractConst: "${name}" not found in chat.js`);
  const extracted = m[0].trim().replace(/^export\s+/, '');
  if (/\bfunction\s/.test(extracted)) {
    throw new Error(`extractConst: "${name}" extraction swallowed a function — the terminator desynced`);
  }
  return extracted;
}

// The real shell escaper's contract, reproduced faithfully. Deliberately NOT
// a pass-through: §8's positive control proves that a value reaching markup
// UNESCAPED would be observable, so a green there is not vacuous.
function escapeHtmlStub(s) {
  return String(s === undefined || s === null ? '' : s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * A minimal QUOTE-AWARE tag scanner: returns `[{name, attrs:[...]}]`.
 *
 * Deliberately not a regex. A naive `<[a-zA-Z][^>]*\son[a-z]+=` "no event
 * handler" check reports a FALSE POSITIVE on correctly-escaped output, because
 * `[^>]*` walks straight through an escaped `&gt;` and out of the attribute it
 * was supposed to be bounded by — so the literal, INERT text `onerror=alert(1)`
 * sitting safely inside a quoted, fully-escaped attribute value reads as a live
 * handler. That regex was written first here and failed exactly that way; it is
 * replaced rather than loosened, because the property under test — "no TAG
 * carries an event-handler ATTRIBUTE" — is about parse structure, and only
 * something that respects quoting can decide it.
 */
function scanTags(html) {
  const out = [];
  for (let i = 0; i < html.length; i++) {
    if (html[i] !== '<') continue;
    let j = i + 1;
    if (html[j] === '/') j++;
    let name = '';
    while (j < html.length && /[a-zA-Z0-9]/.test(html[j])) name += html[j++];
    if (!name) continue;
    const attrs = [];
    let cur = '';
    let quote = null;
    for (; j < html.length; j++) {
      const c = html[j];
      if (quote) { if (c === quote) quote = null; continue; }
      if (c === '"' || c === "'") { if (cur.trim()) { attrs.push(cur.trim()); cur = ''; } quote = c; continue; }
      if (c === '>') break;
      if (c === '=' ) { if (cur.trim()) { attrs.push(cur.trim()); cur = ''; } continue; }
      if (/\s/.test(c)) { if (cur.trim()) { attrs.push(cur.trim()); cur = ''; } continue; }
      cur += c;
    }
    if (cur.trim()) attrs.push(cur.trim());
    out.push({ name: name.toLowerCase(), attrs });
    i = j;
  }
  return out;
}

