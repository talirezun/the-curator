/**
 * The FULL, UNGATED catalogue — every model from both providers.
 *
 * ── WHY §3/§4 DRIVE THE CLIENT WITH THIS, NOT WITH A PRE-GATED PAYLOAD ────
 * The first version of this suite fed the client `serverOfferable(keyed)`
 * below, i.e. a payload in which the SERVER had already emptied the unkeyed
 * provider's list. Every §3/§4 key-scoping assertion passed — and kept passing
 * with BOTH of the client's own key-scoping layers deleted (proven by
 * mutation: 0 and 2 reds respectively, none of them from §3/§4). They were
 * asserting on the fixture, not on the code: with nothing to leak in the
 * input, no client-side leak was expressible. That is this repo's named
 * decorative-guard shape, found inside the suite written to prevent it.
 *
 * The client's scoping is not redundant with the server's: it is the layer
 * that holds if the server one ever regresses, which is exactly the v3.0.13
 * bug's territory. So the primary fixture is the ungated catalogue, and the
 * server-gated payload is kept as a separate COMPOSITION control below.
 */
function rawFull() {
  const out = {};
  for (const p of ALL_PROVIDERS) out[p] = REAL[p].slice();
  return out;
}
/** The `offerable` field exactly as GET /api/config/api-keys builds it today. */
function serverOfferable(keyed) {
  const out = {};
  for (const p of ALL_PROVIDERS) out[p] = keyed.includes(p) ? REAL[p].slice() : [];
  return out;
}
/** Build the menu the way the view does, with the CLIENT doing the scoping. */
function menuFor(keyed, selectedId = null) {
  const norm = normalizeOfferable(rawFull(), keyed);
  return { norm, html: renderModelMenuHtml(norm, keyed, selectedId) };
}

