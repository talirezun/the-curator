/**
 * test-next-composer-model.js — OFFLINE suite for the /next chat composer's
 * MODEL picker (src/public/next/views/chat.js).
 *
 * No network, no API key, no server, no browser, no LLM call. The real, live
 * helpers (`normalizeOfferable`, `offerableEntries`, `resolveChatModel`,
 * `formatPricePerM`, `formatLivePrice`, `formatPromotionRise`,
 * `isFlaggedModel`, `renderModelOptionHtml`, `renderModelMenuHtml`) are
 * extracted from source by brace-matching and executed standalone with
 * `new Function` — the same technique scripts/test-next-provider-rows.js and
 * scripts/test-chat-markdown.js use for browser-side code.
 *
 * The catalogue this suite drives them with is the REAL, live
 * `OFFERABLE_MODELS` table imported from src/brain/llm.js — never a hardcoded
 * model list. Every per-entry assertion below is generated by walking that
 * table, so a model added, repriced, reflagged or promoted in llm.js is
 * covered here the moment it lands, and this suite cannot silently drift into
 * testing a catalogue that no longer ships.
 *
 * ── WHAT THIS SURFACE IS, AND THE GATE IT SHIPPED BEHIND ─────────────────
 * The composer has carried a per-chat PROVIDER dropdown since v3.0.11. This
 * change extends it to a per-chat MODEL choice, rendering each model's LIVE
 * (promotion-resolved) price and, for any model carrying a measured caveat,
 * that caveat verbatim.
 *
 * `MODEL_PICKER_ENABLED` is `true` as of v3.13.0: the backend now honours a
 * model on the chat path (`normalizeChatModel` in src/brain/chat.js, threaded
 * through `sendMessage`/`generateText` and destructured by
 * `POST /api/chat/:domain`). Before that landed, this constant was held at
 * `false` for a real reason, kept here because it explains why this whole
 * suite exists rather than a smaller one: a picker that quotes "$5/$25" and
 * is silently served the $1/$5 default would be a falsehood about capability
 * AND money, and this repo has shipped inert-looking controls before (see
 * chat.js's own header comment on `MODEL_PICKER_ENABLED` for the fuller
 * record).
 *
 * THIS SUITE FORCES THE GATE ON regardless of the constant's live value — the
 * renderers are pure and take every input as a parameter — which is exactly
 * what let it certify the surface BEFORE the flip: the constant going from
 * `false` to `true` in v3.13.0 shipped an already-proven feature, not one
 * that had never been run. §9 below is the drift guard that would have
 * failed loudly had the backend landed without the constant being flipped.
 *
 * ── WHAT IS ASSERTED, AND HOW ────────────────────────────────────────────
 * Everything below DRIVES the real extracted functions. Nothing here greps the
 * source for the shape of a fix — a test that proves a line of source exists
 * proves nothing about what it does (CLAUDE.md, v3.0.17).
 *
 *   §1  Extraction + real-catalogue sanity.
 *   §2  Fixture self-check — the two providers' entries are distinguishable,
 *       and the real catalogue actually CONTAINS the cases §5–§8 depend on
 *       (a flagged entry, a promoted entry, a dominated entry). A green in
 *       those sections must not be able to mean "the case never occurred".
 *   §3  KEY SCOPING — zero saved keys → no dropdown; one key → only that
 *       provider's models; two keys → both. Driven through the real
 *       `normalizeOfferable` + `renderModelMenuHtml`.
 *   §4  THE v3.0.13 REGRESSION GUARD — a model belonging to a provider with
 *       no saved key is NOT selectable: `resolveChatModel` refuses it, and it
 *       never reaches the rendered menu. Asserted for every entry of the
 *       unkeyed provider in the real table, in both directions (gemini-only
 *       and anthropic-only), so a fix special-casing one provider is caught.
 *   §5  PRICE HONESTY — for every entry in the real table, the rendered price
 *       is the LIVE `input`/`output`. For every PROMOTED entry (where the two
 *       differ), the standard price must NOT be rendered as the current one.
 *   §6  PROMOTION DISCLOSURE — every promoted entry renders the coming rise
 *       (the standard price and the date it applies).
 *   §7  MEASURED NOTES — every flagged entry (`suitability !== 'general'` or
 *       `dominated`) renders its note VERBATIM (modulo escaping), and no
 *       flagged model is filtered out of the menu.
 *   §8  ESCAPING — hostile `label` / `note` / `id` containing HTML
 *       metacharacters cannot break out of the markup, with a positive control
 *       proving the harness's escaper would otherwise let them through.
 *   §9  BACKEND-CAPABILITY DRIFT GUARD — see its own header.
 *   §10 THE ANSWER LABEL — which model actually wrote each message.
 *   §11 THE ANSWER COST — what each message cost, priced from its OWN recorded
 *       tokens and the SERVED model's live price. §11.1 proves the view's
 *       arithmetic against the REAL `chargeForItem` lifted out of
 *       src/brain/ingest-queue.js, so the deliberate mirror of a money formula
 *       is MEASURED rather than promised.
 *   §0  FN_NAMES COMPLETENESS — the harness's own blind spot, closed. A helper
 *       missing from FN_NAMES used to CRASH this suite with a ReferenceError
 *       instead of failing it (the v3.11.0 shape); it is now a named red.
 *
 * ── ENFORCED ─────────────────────────────────────────────────────────────
 *   - Key scoping in BOTH directions, over the real catalogue.
 *   - Live price rendered, standard price not passed off as current.
 *   - Coming rise disclosed on every promoted entry.
 *   - Measured note rendered on every flagged entry; flagged models shown.
 *   - Every server-supplied string escaped before it enters markup.
 *
 *   - The per-answer COST is silent whenever any component is missing (§11.3,
 *     §11.4), uses today's promotion-resolved price (§11.5), never renders a
 *     non-zero charge as $0.0000 (§11.6), and comes from the shared formatter
 *     rather than a local one (§11.7).
 *
 * ── NOT ENFORCED (stated rather than implied away) ───────────────────────
 *   - The per-answer cost prices at RENDER time, so a turn served during a
 *     promotion and re-read after it expires prices at the standing (higher)
 *     rate. That direction is deliberate — every price failure in this repo
 *     resolves upward — but it is an approximation and nothing here asserts
 *     the historical rate, because the record does not carry one.
 *   - The Anthropic 0.1x cached-read multiplier is applied to Gemini's
 *     implicit-cache reads too. Inherited unchanged from `chargeForItem` (see
 *     messageCostUsd's docblock); §11.1 pins the two together, which means it
 *     also pins the approximation. Fixing it is a change to the server formula,
 *     not to this view.
 *   - The click handler, the localStorage round-trip and `applyApiKeys` are
 *     NOT executed here: they read module state and `document`/`localStorage`
 *     directly rather than taking them as parameters, so extracting them would
 *     mean re-creating most of the view. The SELECTION GATE they depend on
 *     (`resolveChatModel`) is what actually decides selectability, and it is
 *     driven directly in §4. The handler's re-validation at click time is
 *     covered only by the browser pass, not by this suite.
 *   - This suite does not itself DRIVE `POST /api/chat/:domain` to prove the
 *     backend honours a model end-to-end (no server, no network — see the
 *     top of this file); it proves the render/selection surface is correct
 *     and, via §9, that the gate constant tracks the backend's real
 *     capability. §9 detects drift only via a naming convention (see its
 *     own header); a backend that lands model support WITHOUT a
 *     model-named export on `__testing` would leave the gate shut and this
 *     suite green — that is the SAFE direction (no inert control), and it
 *     is recorded here rather than assumed away. The live backend-to-UI
 *     path is covered by `src/brain/chat.js`'s own suite plus manual/browser
 *     verification, not by this file.
 *   - CSS, layout, focus rings, dark/light rendering and the outside-click /
 *     Escape behaviour are browser concerns, verified by hand, not here.
 */

