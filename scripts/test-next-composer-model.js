section('§8  Escaping — hostile catalogue strings cannot break out');
// ═════════════════════════════════════════════════════════════════════════
{
  const XSS = '"><img src=x onerror=alert(1)>';
  const hostile = {
    id: 'evil-' + XSS,
    provider: 'gemini',
    label: XSS,
    note: '<script>alert(2)</script>',
    suitability: '<b>caution</b>',
    dominated: true,
    thinks: true,
    input: 1, output: 2,
    standardInput: 3, standardOutput: 4,
    promotionUntilIso: '2027-01-01<script>',
    standardPriceFromIso: '2027-01-02"onload="x',
  };
  const html = renderModelOptionHtml('gemini', hostile, null);
  ok(!html.includes('<img src=x'), 'hostile label does not emit a raw <img> tag');
  ok(!html.includes('<script>'), 'hostile note does not emit a raw <script> tag');
  // The real property is not "the substring `onerror=` is absent" — that
  // substring carries no HTML metacharacters, so it legitimately survives as
  // INERT TEXT inside an escaped node, and asserting on it would fail for a
  // correctly-escaped renderer. What must hold is that no TAG in the output
  // carries an event-handler attribute, and that the only tags emitted are the
  // ones this renderer itself writes.
  // Harness self-check FIRST: prove the scanner both parses real tags and
  // WOULD catch a live handler, so the greens below are a finding, not a
  // scanner that silently parses nothing.
  {
    const probe = scanTags('<img src=x onerror="alert(1)"><a href="#" onclick=go()>t</a>');
    ok(probe.length === 3 && probe[0].name === 'img' && probe[1].name === 'a',
      'control: scanTags parses tag names out of real markup');
    ok(probe[0].attrs.includes('onerror') && probe[1].attrs.includes('onclick'),
      'control: scanTags WOULD detect a live event-handler attribute');
    const inert = scanTags('<span title="onerror=alert(1)">x</span>');
    ok(inert.length === 2 && !inert[0].attrs.includes('onerror'),
      'control: scanTags does NOT mistake an escaped, quoted VALUE for a handler attribute');
  }

  const tags = scanTags(html);
  const tagNames = new Set(tags.map(t => t.name));
  ok([...tagNames].every(t => t === 'button' || t === 'span'),
    `only the renderer's own <button>/<span> tags are emitted (found: ${[...tagNames].join(', ')})`);
  const handlerAttrs = tags.flatMap(t => t.attrs).filter(a => /^on[a-z]+$/i.test(a));
  ok(handlerAttrs.length === 0,
    `no emitted TAG carries an event-handler attribute (found: ${handlerAttrs.join(', ') || 'none'})`);
  ok(tags.every(t => t.attrs.every(a => /^[a-z][a-z0-9-]*$/i.test(a))),
    'every emitted attribute name is well-formed — no hostile value split into a new attribute');
  ok(!/<b>caution<\/b>/.test(html), 'hostile suitability does not emit raw markup');
  ok(html.includes('&lt;script&gt;'), 'the note is present but escaped');
  ok(html.includes('&quot;&gt;&lt;img'), 'the label is present but escaped');
  // Attribute integrity: exactly one data-model-id attribute, and the value
  // cannot terminate early into a new attribute.
  ok((html.match(/data-model-id="/g) || []).length === 1, 'exactly one data-model-id attribute is emitted');
  const attr = /data-model-id="([^"]*)"/.exec(html);
  ok(attr && attr[1] === escapeHtmlStub(hostile.id), 'the data-model-id value is the fully escaped id');
  // Positive control: the harness escaper is NOT a pass-through, so the greens
  // above are caused by escaping and not by the payload being inert.
  ok(escapeHtmlStub(XSS) !== XSS, 'control: the escaper actually transforms the hostile payload');
  ok(XSS.includes('<img src=x'), 'control: the raw payload WOULD be detected if it reached the markup unescaped');
  // Whole-menu path escapes too.
  const menu = renderModelMenuHtml(
    normalizeOfferable({ gemini: [hostile], anthropic: [] }, ['gemini']), ['gemini'], null);
  ok(!menu.includes('<img src=x') && !menu.includes('<script>'), 'renderModelMenuHtml escapes just as the row renderer does');
}

